CREATE TABLE `tbl_os_ocorrencia_movimento` (
  `ID_TBL_OS_OCORRENCIA_MOVIMENTO` int(11) NOT NULL AUTO_INCREMENT,
  `ID_SYSTEM_CLIENTE` int(11) NOT NULL,
  `ID_TBL_PEDIDO` int(11) NOT NULL,
  `ID_EQUIPAMENTO` int(11) NOT NULL,
  `ID_TBL_OS_OCORRENCIA` int(11) NOT NULL,
  `ID_TBL_PEDIDO_MOVIMENTO` int(11) NOT NULL,
  `ID_USUARIO` int(11) NOT NULL,
  `DATADOCADASTRO` datetime NOT NULL DEFAULT current_timestamp(),
  PRIMARY KEY (`ID_TBL_OS_OCORRENCIA_MOVIMENTO`),
  UNIQUE KEY `uq_os_oc_mov_par` (`ID_TBL_OS_OCORRENCIA`,`ID_TBL_PEDIDO_MOVIMENTO`),
  KEY `ix_os_oc_mov_contexto` (`ID_SYSTEM_CLIENTE`,`ID_TBL_PEDIDO`,`ID_EQUIPAMENTO`,`ID_TBL_OS_OCORRENCIA`),
  KEY `ix_os_oc_mov_item` (`ID_SYSTEM_CLIENTE`,`ID_TBL_PEDIDO`,`ID_TBL_PEDIDO_MOVIMENTO`),
  CONSTRAINT `fk_os_oc_mov_ocorrencia` FOREIGN KEY (`ID_SYSTEM_CLIENTE`, `ID_TBL_PEDIDO`, `ID_EQUIPAMENTO`, `ID_TBL_OS_OCORRENCIA`) REFERENCES `tbl_os_ocorrencias` (`ID_SYSTEM_CLIENTE`, `ID_TBL_PEDIDO`, `ID_EQUIPAMENTO`, `ID_TBL_OS_OCORRENCIA`),
  CONSTRAINT `ck_os_oc_mov_ids` CHECK (`ID_SYSTEM_CLIENTE` > 0 and `ID_TBL_PEDIDO` > 0 and `ID_EQUIPAMENTO` > 0 and `ID_TBL_OS_OCORRENCIA` > 0 and `ID_TBL_PEDIDO_MOVIMENTO` > 0 and `ID_USUARIO` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
