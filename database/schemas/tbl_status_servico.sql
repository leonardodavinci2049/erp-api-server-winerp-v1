CREATE TABLE `tbl_status_servico` (
  `ID_TBL_STATUS_SERVICO` int(11) NOT NULL AUTO_INCREMENT,
  `ID_SYSTEM_CLIENTE` int(11) NOT NULL,
  `ID_STATUS_OS` int(11) NOT NULL,
  `STATUS_OS` varchar(100) NOT NULL,
  `INATIVO` tinyint(1) NOT NULL DEFAULT 0,
  `DATADOCADASTRO` datetime NOT NULL DEFAULT current_timestamp(),
  `DT_UPDATE` datetime DEFAULT NULL ON UPDATE current_timestamp(),
  `ID_SETOR` int(11) DEFAULT 0,
  `SETOR` varchar(100) DEFAULT NULL,
  `COR_STATUS` varchar(7) DEFAULT NULL,
  PRIMARY KEY (`ID_TBL_STATUS_SERVICO`),
  UNIQUE KEY `UK_STATUS_SERVICO_CLIENTE_STATUS` (`ID_SYSTEM_CLIENTE`,`ID_STATUS_OS`),
  KEY `IDX_STATUS_SERVICO_DESCRICAO` (`ID_SYSTEM_CLIENTE`,`STATUS_OS`)
) ENGINE=InnoDB AUTO_INCREMENT=9 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Cadastro dos status tecnicos das ordens de servico';
