CREATE TABLE `tbl_os_ocorrencias` (
  `ID_TBL_OS_OCORRENCIA` int(11) NOT NULL AUTO_INCREMENT,
  `ID_SYSTEM_CLIENTE` int(11) NOT NULL,
  `ID_TBL_PEDIDO` int(11) NOT NULL,
  `ID_EQUIPAMENTO` int(11) NOT NULL,
  `TIPO_OCORRENCIA` enum('DEFEITO','SOLUCAO','CONDICAO') NOT NULL,
  `ID_OCORRENCIA_ORIGEM` int(11) DEFAULT NULL,
  `TITULO` varchar(200) NOT NULL,
  `DESCRICAO` longtext NOT NULL,
  `RESULTADO_TESTE` longtext DEFAULT NULL,
  `RESOLVIDO` tinyint(4) NOT NULL DEFAULT 0,
  `DT_RESOLUCAO` datetime DEFAULT NULL,
  `ID_USUARIO_RESOLUCAO` int(11) DEFAULT NULL,
  `ID_USUARIO` int(11) NOT NULL,
  `DATADOCADASTRO` datetime NOT NULL DEFAULT current_timestamp(),
  `DT_UPDATE` datetime DEFAULT NULL ON UPDATE current_timestamp(),
  `INATIVO` tinyint(4) NOT NULL DEFAULT 0,
  PRIMARY KEY (`ID_TBL_OS_OCORRENCIA`),
  UNIQUE KEY `uq_os_oc_contexto` (`ID_SYSTEM_CLIENTE`,`ID_TBL_PEDIDO`,`ID_EQUIPAMENTO`,`ID_TBL_OS_OCORRENCIA`),
  KEY `ix_os_oc_equipamento` (`ID_SYSTEM_CLIENTE`,`ID_EQUIPAMENTO`,`DATADOCADASTRO`),
  KEY `ix_os_oc_origem` (`ID_SYSTEM_CLIENTE`,`ID_TBL_PEDIDO`,`ID_EQUIPAMENTO`,`ID_OCORRENCIA_ORIGEM`),
  CONSTRAINT `fk_os_oc_origem` FOREIGN KEY (`ID_SYSTEM_CLIENTE`, `ID_TBL_PEDIDO`, `ID_EQUIPAMENTO`, `ID_OCORRENCIA_ORIGEM`) REFERENCES `tbl_os_ocorrencias` (`ID_SYSTEM_CLIENTE`, `ID_TBL_PEDIDO`, `ID_EQUIPAMENTO`, `ID_TBL_OS_OCORRENCIA`),
  CONSTRAINT `ck_os_oc_ids` CHECK (`ID_SYSTEM_CLIENTE` > 0 and `ID_TBL_PEDIDO` > 0 and `ID_EQUIPAMENTO` > 0 and `ID_USUARIO` > 0),
  CONSTRAINT `ck_os_oc_tipo` CHECK (`TIPO_OCORRENCIA` in ('DEFEITO','SOLUCAO','CONDICAO')),
  CONSTRAINT `ck_os_oc_conteudo` CHECK (char_length(trim(`TITULO`)) > 0 and char_length(trim(`DESCRICAO`)) > 0),
  CONSTRAINT `ck_os_oc_origem` CHECK (`TIPO_OCORRENCIA` = 'SOLUCAO' and `ID_OCORRENCIA_ORIGEM` is not null or `TIPO_OCORRENCIA` in ('DEFEITO','CONDICAO') and `ID_OCORRENCIA_ORIGEM` is null),
  CONSTRAINT `ck_os_oc_flags` CHECK (`RESOLVIDO` in (0,1) and `INATIVO` in (0,1)),
  CONSTRAINT `ck_os_oc_resolucao` CHECK (`RESOLVIDO` = 0 and `DT_RESOLUCAO` is null and `ID_USUARIO_RESOLUCAO` is null or `TIPO_OCORRENCIA` = 'DEFEITO' and `RESOLVIDO` = 1 and `DT_RESOLUCAO` is not null and `ID_USUARIO_RESOLUCAO` is not null and `ID_USUARIO_RESOLUCAO` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
